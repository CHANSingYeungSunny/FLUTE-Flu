#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""make_llm_lanes.py — turn the weights manifest into ready-to-`sbatch` LLM lanes.

WHY THIS FILE EXISTS
--------------------
The 168 LLM cells (14 arms x 4 horizons x 3 seeds) are blocked on two questions
that must be answered *before* a GPU is booked: (1) **can this architecture emit
per-layer hidden states at all** (otherwise the frozen-encoder adapter cannot use
it), and (2) **what does one cell cost**. Both answers live in
`weights_manifest.json` (`status`/`reason`) and
`measured_llm_forward_*.json` (s/ prompt), which are produced on CPU by
`cpu_download_worker.sh` and `measure_llm_forward.py`.

This generator reads those two files and writes, per **SUPPORTED** arm, a
12-cell driver script `llm_lane_<slug>.sh` that tomorrow only needs
`sbatch llm_lane_<slug>.sh`. It never guesses: an arm with no `OK` entry gets
`SKIP <model>: <reason>` on stdout and no script.

Emitted script contract
-----------------------
* gres-free header, `--partition=stingy` (paper-eligible, rule 13(a)), wall sized
  from the measured per-cell cost with a floor;
* memory sized to the checkpoint (`params_b x 2.5 GB`, rounded up) with
  `mem <= cpus x 1024` MB so the same header stays placeable on `tiny`/`batch`;
* an **A100 assert** before any cell (`torch.cuda.get_device_name(0)` must
  contain `A100`; rule 13(a)) — a lane that lands on a V100 aborts instead of
  producing an invalid row;
* `--arm-label <label>`, `--llm-model-id`, `--llm-revision <pinned sha>`,
  `--encoder-batch-size <registry value>`, `--profile author_966`,
  `--containment strict`, `--export-dir hpc_results/expanded_runs`;
* the right interpreter: `mlflu_llm` **only** for the `qwen3_5` family
  (`Qwen/Qwen3.8-27B-FP8`), `mlflu_hpc` (conda) for everything else;
* the expected per-cell wall printed as a comment, from the measured JSON.

Usage
-----
    python hpc_experiments/make_llm_lanes.py \
        --manifest /home/sychan552/scratch/mlflu_weights/weights_manifest.json \
        --measured /home/sychan552/scratch/mlflu_weights/measured_llm_forward_qwen25_1p5b.json \
        --out-dir  /gpfs1/home/sychan552/stage5_a2_durable/code/llm_lanes
    python hpc_experiments/make_llm_lanes.py --manifest M --dry-run   # print only
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_REGISTRY = os.path.join(HERE, "queue", "arms_registry.json")

#: Interpreter per env tag. `hpc` is a CONDA env (transformers 4.57.6 + pandas),
#: `llm` is the venv (transformers 5.x, no pandas) — docs/LLM_ARMS.md §7.1.
ENVS = {
    "hpc": "/home/sychan552/.conda/envs/mlflu_hpc/bin/python",
    "llm": "/home/sychan552/.venvs/mlflu_llm/bin/python",
}

#: Arms whose architecture needs the `qwen3_5` transformers line.
QWEN3_5_HINTS = ("Qwen3.8", "Qwen3_5", "Qwen3.5")

HORIZONS = (24, 36, 48, 60)
SEEDS = (42, 43, 44)


def env_for(arm: dict) -> str:
    """`llm` for the qwen3_5 family, `hpc` otherwise (per the routing rule)."""
    hf = arm.get("hf_id", "")
    if arm.get("venv") == "llm" or any(h in hf for h in QWEN3_5_HINTS):
        return "llm"
    return "hpc"


def mem_and_cpus(params_b: float) -> tuple:
    """`(cpus, mem_MB)` for a checkpoint of `params_b` — keeps mem <= cpus*1024."""
    need_mb = int(max(8.0, float(params_b or 3.0) * 2.5) * 1024)
    cpus = max(8, (need_mb + 1023) // 1024)
    mem = min(need_mb, cpus * 1024)
    return cpus, mem


def cell_seconds(params_b: float, measured: dict) -> float:
    """Projected seconds per cell from a measured 1.5 B-class cost (linear in params)."""
    base = measured.get("cell_seconds")
    if not base:
        return 0.0
    base_params = float(measured.get("measured_params_b") or 1.5)
    return float(base) * (max(float(params_b or base_params), 0.1) / base_params)


def script_for(arm: dict, entry: dict, measured: dict, repo_root: str) -> str:
    """Render one 12-cell lane script."""
    label = arm["label"]
    hf_id = arm["hf_id"]
    params_b = float(arm.get("params_b") or 3.0)
    env = env_for(arm)
    py = ENVS[env]
    bs = int(arm.get("encoder_batch_size") or 8)
    rev = entry.get("revision")
    cpus, mem = mem_and_cpus(params_b)
    cell_s = cell_seconds(params_b, measured)
    wall_h = max(4, int((cell_s * 12) / 3600.0) + 1) if cell_s else 12
    lines = [
        "#!/bin/bash",
        "# =============================================================================",
        f"# llm_lane_{label}.sh — 12 cells (4 horizons x 3 seeds) for {hf_id}",
        "# GENERATED by hpc_experiments/make_llm_lanes.py — do not hand-edit.",
        "#",
        f"# status in the weights manifest : {entry.get('status')}",
        f"# pinned revision                : {rev}",
        f"# env                            : {env}  ({py})",
        f"# encoder batch size             : {bs}",
        f"# measured per-cell projection   : "
        + (f"{cell_s/60:.1f} min (from {measured.get('model_id')})" if cell_s
           else "UNMEASURED — run measure_llm_forward.py first"),
        f"# projected lane wall            : ~{cell_s*12/3600:.1f} h of compute "
        f"(request {wall_h} h)",
        "#",
        "# RULE 13(a): this lane produces paper numbers, so it must run on an A100 in",
        "# `stingy` (or `gpu_a100` if its start is short). The A100 assert below",
        "# aborts the lane on any other GPU instead of emitting an invalid row.",
        "# =============================================================================",
        "#SBATCH --job-name=mlflu_llm_" + label,
        "#SBATCH --partition=stingy",
        "#SBATCH --nodes=1",
        "#SBATCH --ntasks=1",
        f"#SBATCH --cpus-per-task={cpus}",
        f"#SBATCH --mem={mem}M",
        f"#SBATCH --time={wall_h}:00:00",
        f"#SBATCH --output=logs/llm_{label}_%j.out",
        f"#SBATCH --error=logs/llm_{label}_%j.err",
        "#SBATCH --gres=gpu:a100:1",
        "",
        "set -uo pipefail",
        f"REPO=${{REPO:-{repo_root}}}",
        f'PY="${{PY:-{py}}}"',
        f'cd "$REPO" || {{ echo "FATAL: no repo at $REPO"; exit 66; }}',
        'mkdir -p logs hpc_results/expanded_runs',
        "",
        'echo "[lane] host=$(hostname) job=${SLURM_JOB_ID:-LOCAL} part=${SLURM_JOB_PARTITION:-?}"',
        '"$PY" - <<\'PYEOF\'',
        "import torch, sys",
        "if not torch.cuda.is_available():",
        "    sys.exit('FATAL: no CUDA device on this node')",
        "name = torch.cuda.get_device_name(0)",
        "print('[lane] gpu =', name, 'capability =', torch.cuda.get_device_capability(0))",
        "if 'A100' not in name:",
        "    sys.exit('FATAL rule 13(a): this lane needs an A100, got %r -- refusing to "
        "produce an invalid row' % name)",
        "PYEOF",
        '[ $? -eq 0 ] || { echo "[lane] A100 assert failed"; exit 65; }',
        "",
    ]
    for L in HORIZONS:
        for S in SEEDS:
            lines += [
                f'echo "=== cell L={L} seed={S} ==="',
                '"$PY" scripts/train_backbone_966.py \\',
                "    --backbone llm_encoder \\",
                f"    --arm-label {label} \\",
                f"    --llm-model-id {hf_id} \\",
                (f"    --llm-revision {rev} \\" if rev else
                 "    --llm-allow-unpinned \\"),
                "    --horizon " + str(L) + " --seed " + str(S) + " \\",
                "    --profile author_966 --containment strict \\",
                f"    --encoder-batch-size {bs} \\",
                f"    --export-dir hpc_results/expanded_runs/{label}_L{L}_s{S} \\",
                f"    --ckpt-dir    checkpoints/llm/{label}_L{L}_s{S}",
                'rc=$?; echo "=== cell L=' + str(L) + " seed=" + str(S) + ' rc=$rc ==="',
                "",
            ]
    lines += ['echo "=== lane ' + label + ' done job=${SLURM_JOB_ID:-LOCAL} ==="', "exit 0", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Emit one 12-cell sbatch lane per SUPPORTED LLM arm.")
    ap.add_argument("--manifest", required=True,
                    help="weights_manifest.json (merged) from weights_worker.py")
    ap.add_argument("--registry", default=DEFAULT_REGISTRY)
    ap.add_argument("--measured", default=None,
                    help="measured_llm_forward_*.json (for the wall estimate)")
    ap.add_argument("--out-dir", default=None)
    ap.add_argument("--repo-root", default="/gpfs1/home/sychan552/stage5_a2_durable")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)

    with open(a.manifest, "r", encoding="utf-8") as fh:
        manifest = json.load(fh)
    with open(a.registry, "r", encoding="utf-8") as fh:
        registry = json.load(fh)
    measured = {}
    if a.measured and os.path.exists(a.measured):
        with open(a.measured, "r", encoding="utf-8") as fh:
            measured = json.load(fh)

    entries = {e.get("model"): e for e in manifest.get("entries", [])}
    written, skipped = [], []
    for arm in registry.get("arms", []):
        hf_id, label = arm["hf_id"], arm["label"]
        e = entries.get(hf_id)
        status = (e or {}).get("status")
        if status != "OK":
            reason = (e or {}).get("reason") or ("not downloaded yet"
                                                 if e is None else status)
            skipped.append((hf_id, label, reason))
            continue
        if a.dry_run:
            print(f"[dry-run] would write llm_lane_{label}.sh for {hf_id} "
                  f"(env={env_for(arm)}, {cell_seconds(arm.get('params_b'), measured)/60:.1f} min/cell)")
            written.append(label)
            continue
        if not a.out_dir:
            raise SystemExit("--out-dir is required unless --dry-run")
        os.makedirs(a.out_dir, exist_ok=True)
        path = os.path.join(a.out_dir, f"llm_lane_{label}.sh")
        body = script_for(arm, e, measured, a.repo_root)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
        os.chmod(path, 0o755)
        written.append(label)
        print(f"[lane] wrote {path}")

    print(f"\n[lanes] ready={len(written)} skipped={len(skipped)} "
          f"cells={len(written)*len(HORIZONS)*len(SEEDS)}")
    for hf_id, label, reason in skipped:
        print(f"  SKIP {hf_id} ({label}): {reason}")
    if not written:
        print("[lanes] NOTHING READY — no arm has status=OK in this manifest")
        return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
