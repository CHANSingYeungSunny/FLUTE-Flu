"""
D1 regression test — explicit pilot-spec metadata (implementation source v2.2)
=============================================================================

Defect D1 (pilot-definition audit): each of the four entries in
`hpc_scripts/pilot_specs.json` was missing

  * `experiment_stage`
  * `test_access_allowed`
  * `protocol_version`

...and the top-level object carried `scientific_protocol_version` but no
`protocol_version`.

This test FAILS if the defect ever returns. It asserts, against the file that is
actually shipped (regenerated by `hpc_specs.generate()`):

  1 the top-level object carries all three mandated fields, with the mandated
    values (`pilot` / `false` / the scientific protocol version);
  2 EVERY individual pilot spec carries the same three fields explicitly;
  3 model keys, horizons and seeds are UNCHANGED by the v2.2 bump;
  4 `selection_eligible` stays false everywhere (pilot is infrastructure
    evidence, never a ranking);
  5 `test_access_allowed` is false and can never be true for a validation-phase
    run status (`runner._eligibility`).
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
import typing as _t

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _bootstrap  # noqa: F401,E402

from innovation import run_artifacts as ART  # noqa: E402
from innovation import runner as RUN  # noqa: E402
from innovation.paths import (PILOT_EXPERIMENT_STAGE, PROTOCOL_VERSION,  # noqa: E402
                              PROJECT_ROOT, TEST_ACCESS_ALLOWED,
                              pilot_spec_metadata)
from innovation.run_id import parse_run_id  # noqa: E402

PILOT_SPECS_PATH = os.path.join(PROJECT_ROOT, "hpc_scripts", "pilot_specs.json")

# D1: the exact field set that must be present, explicitly, at BOTH levels.
MANDATED = ("experiment_stage", "test_access_allowed", "protocol_version")

# unchanged by the v2.2 bump
EXPECTED_SPECS = (
    ("nlinear", "none", "identity", 24, 42),
    ("gpt2_miflu", "gpt2", "concat_projection", 24, 42),
    ("dlinear", "none", "identity", 24, 42),
    ("patchtst", "none", "identity", 24, 42),
    ("itransformer", "none", "identity", 24, 42),
    ("qwen_time_llm", "none", "identity", 24, 42),
    ("calf_llm", "none", "identity", 24, 42),
    ("timecma_llm", "none", "identity", 24, 42),
)


def _load() -> dict:
    assert os.path.exists(PILOT_SPECS_PATH), (
        f"{PILOT_SPECS_PATH} missing — run scripts/innovation/hpc_specs.py first")
    with open(PILOT_SPECS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


# 1 ─────────────────────────────────────────────────────────────────────────
def test_top_level_carries_mandated_metadata():
    data = _load()
    for field in MANDATED:
        assert field in data, f"D1: top-level object is missing {field!r}"
    assert data["experiment_stage"] == PILOT_EXPERIMENT_STAGE == "pilot", data
    assert data["test_access_allowed"] is False, data
    assert data["protocol_version"] == PROTOCOL_VERSION, data
    # the pre-existing keys must NOT have been dropped by the repair
    assert data["scientific_protocol_version"] == PROTOCOL_VERSION, data
    assert isinstance(data.get("implementation_source_version"), str), data


# 2 ─────────────────────────────────────────────────────────────────────────
def test_every_spec_carries_mandated_metadata():
    data = _load()
    specs = data["specs"]
    assert len(specs) == 8, f"expected 8 pilot specs, got {len(specs)}"
    for i, spec in enumerate(specs):
        for field in MANDATED:
            assert field in spec, f"D1: spec[{i}] is missing {field!r}: {spec}"
        assert spec["experiment_stage"] == "pilot", spec
        assert spec["test_access_allowed"] is False, spec
        assert spec["protocol_version"] == PROTOCOL_VERSION, spec
        # per-spec traceability kept
        assert spec.get("source_snapshot_sha256"), spec
        assert spec.get("implementation_source_version"), spec


# 3 ─────────────────────────────────────────────────────────────────────────
def test_model_keys_horizons_seeds_unchanged():
    data = _load()
    got = tuple((s["model"], s["text_encoder"], s["fusion"], s["horizon"],
                 s["seed"]) for s in data["specs"])
    assert got == EXPECTED_SPECS, got


# 4 ─────────────────────────────────────────────────────────────────────────
def test_pilot_stays_ineligible_everywhere():
    data = _load()
    assert data["selection_eligible"] is False, data
    for spec in data["specs"]:
        assert spec["selection_eligible"] is False, spec


# 5 ─────────────────────────────────────────────────────────────────────────
def test_run_status_never_allows_test_access():
    """The runtime half of D1: every stage's run_status forbids test access."""
    assert TEST_ACCESS_ALLOWED is False
    for stage in ("smoke", "pilot", "screening", "full", "adhoc", "validation"):
        elig = RUN._eligibility(stage)
        assert elig["test_access_allowed"] is False, (stage, elig)
        assert elig["experiment_stage"] == stage, (stage, elig)
        assert elig["protocol_version"] == PROTOCOL_VERSION, (stage, elig)

        tmp = tempfile.mkdtemp(prefix="innov_d1_status_")
        ART.write_run_status(tmp, status="running", run_id="x", **elig)
        with open(os.path.join(tmp, "run_status.json"), "r",
                  encoding="utf-8") as f:
            written = json.load(f)
        assert written["test_access_allowed"] is False, written
        assert written["experiment_stage"] == stage, written


# 6 ─────────────────────────────────────────────────────────────────────────
def test_metadata_contract_matches_paths_helper():
    """One source of truth: the generator, the snapshot re-stamp and this test
    all read `paths.pilot_spec_metadata()`."""
    meta = pilot_spec_metadata()
    assert set(meta) == set(MANDATED), meta
    assert meta["experiment_stage"] == "pilot", meta
    assert meta["test_access_allowed"] is False, meta
    assert meta["protocol_version"] == PROTOCOL_VERSION, meta


# 7 ─────────────────────────────────────────────────────────────────────────
def test_source_snapshot_restamp_preserves_metadata():
    """Running the snapshot cascade alone must not strip the D1 fields."""
    from innovation import source_snapshot as SS

    data = _load()
    tmp = tempfile.mkdtemp(prefix="innov_d1_stamp_")
    fake = os.path.join(tmp, "pilot_specs.json")
    stripped = json.loads(json.dumps(data))
    for spec in stripped["specs"]:
        for field in MANDATED:
            spec.pop(field, None)
        for field in MANDATED:
            stripped.pop(field, None)
    with open(fake, "w", encoding="utf-8") as f:
        json.dump(stripped, f)

    old_root = SS.PROJECT_ROOT
    SS.PROJECT_ROOT = tmp
    try:
        os.makedirs(os.path.join(tmp, "hpc_scripts"), exist_ok=True)
        os.replace(fake, os.path.join(tmp, "hpc_scripts", "pilot_specs.json"))
        SS.stamp_pilot_specs("a" * 64)
        with open(os.path.join(tmp, "hpc_scripts", "pilot_specs.json"),
                  "r", encoding="utf-8") as f:
            out = json.load(f)
    finally:
        SS.PROJECT_ROOT = old_root
    for field in MANDATED:
        assert field in out, out
    for spec in out["specs"]:
        for field in MANDATED:
            assert field in spec, spec
        assert spec["source_snapshot_sha256"] == "a" * 64, spec


if __name__ == "__main__":
    test_top_level_carries_mandated_metadata()
    test_every_spec_carries_mandated_metadata()
    test_model_keys_horizons_seeds_unchanged()
    test_pilot_stays_ineligible_everywhere()
    test_run_status_never_allows_test_access()
    test_metadata_contract_matches_paths_helper()
    test_source_snapshot_restamp_preserves_metadata()
    print("[test_pilot_spec_metadata] OK")
