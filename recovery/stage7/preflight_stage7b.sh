#!/bin/bash
# Stage 7 preflight part 2: prove the author SOURCE tree is untouched (only
# recompiled .pyc caches differ), and rewrite the A0 GPU invocation to pass the
# author's TRUE argparse defaults verbatim.
set -uo pipefail
A0=/scratch/sychan552/a0_replay
cd "$A0" || exit 1

echo "=== 1. are any author SOURCE files modified? ==="
mod=$(git status --porcelain | grep -v '\.pyc$' || true)
if [ -z "$mod" ]; then
  echo "  NO source file modified. Only __pycache__/*.pyc differ (regenerated by"
  echo "  importing the modules; Python bytecode caches, not part of the release)."
else
  echo "  SOURCE MODIFIED -- investigate:"; echo "$mod" | sed 's/^/    /'
fi
echo
echo "=== 2. full git status (should be .pyc only) ==="
git status --porcelain | sed 's/^/  /'
echo
echo "=== 3. source hashes of the three files that define A0's behaviour ==="
sha256sum main_ILI_lora.py models/GPT4TS_lora.py data_provider/data_loader.py \
          data_provider/data_factory.py models/GPT4TS.py | sed 's/^/  /'
echo
echo "=== 4. the author's argparse defaults, read from the file itself ==="
grep -n "add_argument" main_ILI_lora.py | sed 's/^/  /'
